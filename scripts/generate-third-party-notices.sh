#!/bin/bash
# Regenerates the dependency part of THIRD_PARTY_NOTICES: native libraries
# linked into the app, every Rust crate in the macOS build, and every package
# in the frontend's production dependency tree. The hand-written sections above
# the marker line are kept as they are.
#
# Requires cargo-about (cargo install cargo-about --locked --features cli),
# Bun, and network access to fetch the ONNX Runtime notices.
set -euo pipefail

repo_dir="$(cd "$(dirname "$0")/.." && pwd)"
notices="$repo_dir/THIRD_PARTY_NOTICES"
marker="DEPENDENCY LICENSES (generated by scripts/generate-third-party-notices.sh)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

package_dir() {
  cargo metadata --format-version 1 --manifest-path "$repo_dir/src-tauri/Cargo.toml" \
    | python3 -c 'import json,os,sys; name=sys.argv[1]; print(next(os.path.dirname(p["manifest_path"]) for p in json.load(sys.stdin)["packages"] if p["name"]==name))' "$1"
}

ort_version="$(grep -o -m1 'ms@[0-9.]*' "$(package_dir ort-sys)/build/download/dist.txt" | cut -d@ -f2)"
curl -fsSL -o "$work/ort-license" "https://raw.githubusercontent.com/microsoft/onnxruntime/v$ort_version/LICENSE"
curl -fsSL -o "$work/ort-notices" "https://raw.githubusercontent.com/microsoft/onnxruntime/v$ort_version/ThirdPartyNotices.txt"
ggml_license="$(package_dir transcribe-cpp-sys)/ggml/LICENSE"

(cd "$repo_dir/src-tauri" && cargo about generate --fail about.hbs -o "$work/rust")
(cd "$repo_dir" && bun scripts/npm-licenses.ts > "$work/npm")

rule() { printf '%s\n' "================================================================================"; }
{
  # Everything above the generated section, without its trailing rule/blank lines.
  python3 - "$notices" "$marker" <<'PY'
import sys
text = open(sys.argv[1]).read()
head = text.split(sys.argv[2])[0].rstrip()
print(head.rstrip("=").rstrip())
PY
  echo
  rule
  echo "$marker"
  rule
  echo
  echo "ONNX Runtime $ort_version, statically linked for speech recognition."
  echo "Source: https://github.com/microsoft/onnxruntime"
  echo
  cat "$work/ort-license"
  echo
  echo "ONNX Runtime third-party notices, reproduced from its source:"
  echo
  cat "$work/ort-notices"
  echo
  rule
  echo "ggml, statically linked through transcribe-cpp."
  echo "Source: https://github.com/ggml-org/ggml"
  echo
  cat "$ggml_license"
  echo
  rule
  echo "Rust crates compiled into hushtype for macOS"
  rule
  cat "$work/rust"
  rule
  echo "JavaScript packages in hushtype's interface"
  rule
  cat "$work/npm"
} > "$work/notices"
mv "$work/notices" "$notices"
printf 'Wrote %s (%s lines)\n' "$notices" "$(wc -l < "$notices" | tr -d ' ')"
